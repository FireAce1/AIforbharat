def generate_variations(base_examples, num_variations=20):
    """Generate variations of base examples using simple transformations"""
    variations = base_examples.copy()
    
    # Simple duplication to reach target count
    # In production, use more sophisticated augmentation
    while len(variations) < num_variations:
        variations.extend(base_examples[:num_variations - len(variations)])
    
    return variations[:num_variations]

def create_training_dataset():
    """Create complete training dataset with 100+ examples per intent"""
    dataset = []
    
    for intent, languages in INTENTS_DATA.items():
        for lang, examples in languages.items():
            # Generate variations to reach 100+ examples per intent per language
            all_examples = generate_variations(examples, num_variations=50)
            
            for example in all_examples:
                dataset.append({
                    "text": example,
                    "intent": intent,
                    "language": lang
                })
    
    # Shuffle dataset
    random.shuffle(dataset)
    
    return dataset

def split_dataset(dataset, validation_split=0.2):
    """Split dataset into training and validation sets"""
    split_idx = int(len(dataset) * (1 - validation_split))
    return dataset[:split_idx], dataset[split_idx:]

