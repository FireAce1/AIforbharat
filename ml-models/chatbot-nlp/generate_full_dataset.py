def create_dataset():
    """Create dataset from all intents"""
    dataset = []
    
    for intent, languages in ALL_INTENTS.items():
        for lang, examples in languages.items():
            for example in examples:
                dataset.append({
                    "text": example,
                    "intent": intent,
                    "language": lang
                })
    
    random.shuffle(dataset)
    return dataset

def split_dataset(dataset, validation_split=0.2):
    """Split into train/val"""
    split_idx = int(len(dataset) * (1 - validation_split))
    return dataset[:split_idx], dataset[split_idx:]

if __name__ == "__main__":
    print("Generating complete dataset with all 20 intents...")
    
    dataset = create_dataset()
    print(f"Total examples: {len(dataset)}")
    
    # Count examples per intent
    intent_counts = {}
    for item in dataset:
        intent_counts[item['intent']] = intent_counts.get(item['intent'], 0) + 1
    
    print(f"\nIntents: {len(intent_counts)}")
    print("Examples per intent:")
    for intent, count in sorted(intent_counts.items()):
        print(f"  {intent}: {count}")
    
    # Split
    train_data, val_data = split_dataset(dataset)
    print(f"\nTraining: {len(train_data)}")
    print(f"Validation: {len(val_data)}")
    
    # Save
    with open("data/training_data.json", "w", encoding="utf-8") as f:
        json.dump(train_data, f, ensure_ascii=False, indent=2)
    
    with open("data/validation_data.json", "w", encoding="utf-8") as f:
        json.dump(val_data, f, ensure_ascii=False, indent=2)
    
    print("\nDataset saved successfully!")
